/**
 * Get an SVG icon by its ID
 * @param {string} iconId - The icon identifier
 * @param {number} size - Icon size in pixels (default: 24)
 * @returns {string} SVG HTML string, or empty string if icon not found
 */
export function getIcon(iconId, size = 24) {
  const iconFn = ICON_MAP[iconId];
  if (iconFn) {
    return iconFn(size);
  }
  console.warn(`[Icons] Unknown icon ID: ${iconId}`);
  return '';
}

/**
 * Get an icon wrapped in a span with the icon class
 * Useful for inline display with proper sizing
 * @param {string} iconId - The icon identifier
 * @param {number} size - Icon size in pixels (default: 16)
 * @param {string} className - Additional CSS class (default: '')
 * @returns {string} HTML string with icon in span
 */
export function getIconSpan(iconId, size = 16, className = '') {
  const icon = getIcon(iconId, size);
  const classes = ['icon', className].filter(Boolean).join(' ');
  return `<span class="${classes}">${icon}</span>`;
}

/**
 * Check if an icon ID exists
 * @param {string} iconId - The icon identifier to check
 * @returns {boolean} True if icon exists
 */
export function hasIcon(iconId) {
  return iconId in ICON_MAP;
}

/**
 * Get all available icon IDs
 * @returns {string[]} Array of icon IDs
 */
export function getIconIds() {
  return Object.keys(ICON_MAP);
}

